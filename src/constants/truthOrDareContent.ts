/**
 * Gera apelido de jogo com animal + 4 dígitos (ex: 🦊 Raposa4821)
 */
export function generateGameNick(existingNicks: string[]): { gameNick: string; avatarColor: string } {
  let attempts = 0;
  while (attempts < 50) {
    const animal = ANIMAL_AVATARS[Math.floor(Math.random() * ANIMAL_AVATARS.length)];
    const num = Math.floor(1000 + Math.random() * 9000);
    const candidate = `${animal.emoji} ${animal.name}${num}`;
    if (!existingNicks.includes(candidate)) {
      return { gameNick: candidate, avatarColor: animal.color };
    }
    attempts++;
  }
  const fallbackNum = Math.floor(1000 + Math.random() * 9000);
  return { gameNick: `🦊 Raposa${fallbackNum}`, avatarColor: '#10b981' };
}
